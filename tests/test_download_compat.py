class TestSm3:
    def test_standard_vector_abc(self):
        # GB/T 32905-2016 standard test vector.
        digest = "".join(f"{b:02x}" for b in sm3_to_array("abc"))
        assert digest == (
            "66c7f0f462eeedd9d1f2d46bdc10e4e24167c4875cf2f7a2297da02b8f4ba8e0"
        )

    def test_matches_js_fixture(self, fixture):
        assert sm3_to_array("abc") == fixture["sm3_abc"]
        assert sm3_to_array("中文测试") == fixture["sm3_cjk"]


class TestAbogusCompat:
    def test_signatures_match_js_reference(self, fixture):
        for case in fixture["cases"]:
            bogus = ABogus(fixture["ua"], rng=make_lcg(fixture["seed"])).get_value(
                case["query"], now_ms=fixture["now_ms"]
            )
            assert bogus == case["a_bogus"], f"mismatch for query: {case['query'][:60]}…"

    def test_signature_changes_with_clock(self, fixture):
        query = fixture["cases"][0]["query"]
        a = ABogus(fixture["ua"], rng=make_lcg(1)).get_value(query, now_ms=fixture["now_ms"])
        later = fixture["now_ms"] + 60000
        b = ABogus(fixture["ua"], rng=make_lcg(1)).get_value(query, now_ms=later)
        assert a != b

    def test_js_bytes_cjk_two_bytes(self):
        # JS charCodeAt rule: hanzi (U+4E2D) emits exactly 2 bytes, not UTF-8's 3.
        assert js_bytes("中") == bytes([0x4E, 0x2D])
        assert js_bytes("ab") == b"ab"

    def test_base64_partial_group_emits_len_plus_one(self):
        assert encode_base64(b"\x01") == "Df=="  # 1 byte -> 2 digits
        assert encode_base64(b"\x01\x02") == "Dfm="  # 2 bytes -> 3 digits

    def test_rc4_roundtrip(self):
        data = b"the quick brown fox"
        key = b"\xd3"
        assert rc4(key, rc4(key, data)) == data


class TestWebsignCompat:
    def test_normalize_matches_js(self, fixture):
        raw = "aid=6383&channel=channel_pc_web&uifid=abc-uifid-123&msToken=a%2Bb%3Dc"
        assert normalize_query(raw) == fixture["websign"]["normalized"]
        # literal '+' decodes to '+' (not a space) and re-encodes as %2B
        assert "%2B" in fixture["websign"]["normalized"]
        assert " " not in fixture["websign"]["normalized"]

    def test_sign_matches_js(self, fixture):
        signed, signature = sign(
            "aid=6383&channel=channel_pc_web&uifid=abc-uifid-123",
            "abc-uifid-123",
            timestamp=1759400000,
        )
        assert signed == fixture["websign"]["signed"][0]
        assert signature == fixture["websign"]["signed"][1]
